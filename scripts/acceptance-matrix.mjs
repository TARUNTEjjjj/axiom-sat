// Turn the Playwright JSON report into a dated Markdown matrix of checks × browser engines.
//   npm run test:browser && node scripts/acceptance-matrix.mjs > docs/evidence/acceptance-YYYY-MM-DD/automated.md
// Records only what the run reports: exact engine builds, the OS it ran on and each result.
import { readFile } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import os from 'node:os';

const report = JSON.parse(await readFile(process.argv[2] || 'test-results/results.json', 'utf8'));
const version = async (name) => JSON.parse(await readFile(`node_modules/${name}/package.json`, 'utf8')).version;

function system() {
  if (process.platform === 'darwin') {
    const out = (args) => execFileSync('sw_vers', args, { encoding: 'utf8' }).trim();
    return `macOS ${out(['-productVersion'])} (build ${out(['-buildVersion'])}), ${os.arch()}`;
  }
  return `${os.type()} ${os.release()}, ${os.arch()}`;
}

const engines = new Map();
const rows = new Map();
function visit(suite, path) {
  const here = suite.title && !suite.title.endsWith('.mjs') ? [...path, suite.title] : path;
  for (const spec of suite.specs || []) {
    const name = [...here, spec.title].join(' › ');
    for (const test of spec.tests) {
      const result = test.results.at(-1);
      const browser = test.annotations.find((a) => a.type === 'browser')?.description;
      if (browser) engines.set(test.projectName, browser);
      if (!rows.has(name)) rows.set(name, { file: spec.file, results: {} });
      rows.get(name).results[test.projectName] = result ? result.status : 'not run';
    }
  }
  for (const child of suite.suites || []) visit(child, here);
}
for (const suite of report.suites) visit(suite, []);

const projects = [...new Set([...rows.values()].flatMap((row) => Object.keys(row.results)))];
const started = new Date(report.stats.startTime);
const mark = { passed: 'pass', failed: '**FAIL**', timedOut: '**FAIL** (timeout)', skipped: 'skipped', interrupted: 'interrupted' };
const lines = [
  `# Automated acceptance run — ${started.toISOString().slice(0, 10)}`,
  '',
  `Generated by \`scripts/acceptance-matrix.mjs\` from the Playwright JSON report (\`test-results/results.json\`) of a run started ${started.toISOString()}.`,
  '',
  `- System: ${system()}`,
  `- Node.js ${process.versions.node}; Playwright ${await version('@playwright/test')}; @axe-core/playwright ${await version('@axe-core/playwright')} with axe-core ${await version('axe-core')}`,
  ...projects.map((p) => `- ${p}: ${engines.get(p) || 'version not recorded'}, headless`),
  `- Totals: ${report.stats.expected} passed, ${report.stats.unexpected} failed, ${report.stats.flaky} flaky, ${report.stats.skipped} skipped`,
  '',
  `| Check | ${projects.join(' | ')} |`,
  `| --- | ${projects.map(() => '---').join(' | ')} |`,
  ...[...rows].map(([name, row]) => `| ${name} | ${projects.map((p) => mark[row.results[p]] || row.results[p] || 'not run').join(' | ')} |`),
  '',
];
process.stdout.write(lines.join('\n'));
